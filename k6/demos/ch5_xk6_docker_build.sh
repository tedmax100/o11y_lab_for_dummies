#!/usr/bin/env bash
# ==============================================================================
# Chapter 5 Live Demo: xk6 Docker 確定性編譯指令 (Deterministic Build)
# ==============================================================================
#
# 核心教學亮點：
# 1. 為什麼用 Docker 編譯 xk6？
#    - 團隊成員或 CI/CD Runner 不需額外安裝 Go 語言開發環境。
#    - 確保所有環境建置出來的二進位檔案環境依賴 100% 一致。
# 2. 核心修正避坑點：
#    - 容器掛載路徑必須是 -v $(pwd):/xk6，產生的 k6 二進位檔才會直接留在本機當前目錄！
#    - 加入 -u $(id -u):$(id -g)，產出的執行檔才不會被 root 權限鎖死。
# ==============================================================================

set -euo pipefail

OUTPUT_DIR="$(pwd)/bin"
mkdir -p "${OUTPUT_DIR}"

echo "=========================================================="
echo "📦 正在使用 Docker (grafana/xk6) 編譯擴充套件版 k6..."
echo "🔌 範例擴充：xk6-sql (資料庫原生壓測支援)"
echo "📂 產出路徑：${OUTPUT_DIR}/k6"
echo "=========================================================="

docker run --rm \
  -u "$(id -u):$(id -g)" \
  -v "${OUTPUT_DIR}:/xk6" \
  grafana/xk6 build latest \
  --with github.com/grafana/xk6-sql \
  --output /xk6/k6-custom

echo "=========================================================="
echo "🎉 編譯完成！驗證擴充版本："
echo "   ${OUTPUT_DIR}/k6-custom version"
echo "=========================================================="
